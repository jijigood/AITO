"""
学习版：skills/scenario_router.py

官方对应文件：
    /home/huangxiaolin/AITO/5.4/Track A/skills/scenario_router.py

这个文件的职责非常单一：

    根据 `tag + num_base_stations` 把 scenario 分成 F1/F2/F3/F4 四个家族。

它不是诊断模块，也不看五张表。
它只利用题目元信息做“先验路由”。
"""


# ------------------------------------------------------------------------------
# 1. 为什么要先路由 family
# ------------------------------------------------------------------------------
#
# Track A 表面上每题都有一组候选选项，像是一个较大的分类问题。
# 但训练集里有很强的结构规律：
#
# - 4 BS + single-answer    -> F1
# - 4 BS + multiple-answer  -> F2
# - 5 BS + multiple-answer  -> F3
# - 13 BS + single-answer   -> F4
#
# 这意味着：
# - 有些题从一开始就知道应该输出几个答案
# - 有些动作族在某些 family 里几乎不会出现
# - candidate generation 可以按 family 使用不同策略


# ------------------------------------------------------------------------------
# 2. Family 数据结构
# ------------------------------------------------------------------------------
#
# 官方用 dataclass 表示一个 Family：
#
# - name
#   F1 / F2 / F3 / F4
#
# - num_bs
#   这个家族典型的基站数量。
#
# - is_multiple
#   是否多答案。
#
# - expected_answer_count
#   单选为 1。
#   F3 固定为 4。
#   F2 写成 2，因为大多数是 2 个答案，但实际可能扩到 4。
#
# - description
#   给人读的说明。
#
# - primary_skill_bundle
#   提示后续应该优先用哪类 skill 组合。


# ------------------------------------------------------------------------------
# 3. route() 的规则
# ------------------------------------------------------------------------------
#
# 官方核心逻辑几乎可以写成：
#
#     is_multiple = "multiple" in tag.lower()
#
#     if num_base_stations == 5:
#         return F3
#
#     if num_base_stations == 13:
#         return F4
#
#     if num_base_stations == 4:
#         return F2 if is_multiple else F1
#
#     fallback:
#         return F2 if is_multiple else F1
#
# 注意：
# - `5 BS -> F3` 是很强的硬规则。
# - `13 BS -> F4` 也是很强的硬规则。
# - 真正需要看 tag 的主要是 `4 BS`。


# ------------------------------------------------------------------------------
# 4. expected_answer_count()
# ------------------------------------------------------------------------------
#
# 这个函数返回 `(min_answers, max_answers)`：
#
# - F1: (1, 1)
# - F4: (1, 1)
# - F3: (4, 4)
# - F2: (2, 4)
#
# 它给 candidate generator 一个约束：
# 不同 family 的答案个数不应该由模型自由发挥。


# ------------------------------------------------------------------------------
# 5. 学习时最该记住的点
# ------------------------------------------------------------------------------
#
# `scenario_router.py` 的价值不在代码复杂度，而在它承认了一个事实：
#
#     Track A 不是完全无结构的 22 选项题。
#
# 一旦先分 family，后面的 feature、candidate、verifier 都能更稳定。
