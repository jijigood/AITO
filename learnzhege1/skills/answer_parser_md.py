# ------------------------------------------------------------------------------
# 1. VALID_OPTIONS
# ------------------------------------------------------------------------------
#
# 官方 5.4 文件里写死允许：
#
#     C1, C2, ..., C22
#
# 所以官方代码里的 VALID_OPTIONS 是：
#
#     {f"C{i}" for i in range(1, 23)}
#
# 但 Phase 2 test.json 每题是 `C1-C24`。
# 所以如果你把这个文件用于 Phase 2，应该改成从 `task.options`
# 动态生成合法集合，或者至少扩到 `range(1, 25)`。
#
# 后续 validate 会把超出合法集合、空字符串、非 C-code 都丢掉。


# ------------------------------------------------------------------------------
# 2. extract_boxed_answer(text)
# ------------------------------------------------------------------------------
#
# 作用：
#     从模型输出中提取最后一个 `\\boxed{...}`。
#
# 支持：
#
# - \\boxed{C9}
# - \\boxed{C3|C7}
# - \\boxed{C5|C9|C11|C20}
# - \\boxed{{C9}}
#
# 为什么取最后一个？
# 因为模型可能在推理中间写过一个 tentative answer，
# 最后才给 final answer。


# ------------------------------------------------------------------------------
# 3. validate_and_normalise(answer)
# ------------------------------------------------------------------------------
#
# 作用：
#     检查答案是否合法，并排序。
#
# 例子：
#
# - `C7|C3`       -> `C3|C7`
# - `C22|C1|C10` -> `C1|C10|C22`
# - `C99|C3`     -> `C3`
# - 空 / 全非法  -> `""`
#
# 这个函数非常适合最终提交前跑一遍，避免格式问题白白丢分。


# ------------------------------------------------------------------------------
# 4. parse_answer(text)
# ------------------------------------------------------------------------------
#
# 完整流水线：
#
#     extract_boxed_answer -> validate_and_normalise
#
# 输出：
#
# - `C3`
# - `C3|C7`
# - 或空字符串


# ------------------------------------------------------------------------------
# 5. iou_score(predicted, ground_truth)
# ------------------------------------------------------------------------------
#
# 比赛 README 里的 accuracy 是集合 IOU：
#
#     |pred ∩ gt| / |pred ∪ gt|
#
# 所以：
#
# - pred = C3|C7
# - gt   = C3|C8
#
# intersection = {C3}
# union = {C3, C7, C8}
# score = 1 / 3
#
# 这比旧 `utils.compute_score()` 更贴近真实多答案评分。


# ------------------------------------------------------------------------------
# 6. batch_iou()
# ------------------------------------------------------------------------------
#
# 批量统计：
#
# - mean_iou
# - exact_match_rate
# - scores
#
# 适合你本地评估训练集或带答案验证集。


